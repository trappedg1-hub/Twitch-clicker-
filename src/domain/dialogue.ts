export function pickEmotionForContext(
  boldness: number,
  displayedStage: SubGoalStageIndex,
  seed: number,
): Exclude<HeroineEmotion, 'neutral'> {
  if (boldness < 26 || displayedStage === 0) {
    return seed % 3 === 0 ? 'fluster' : 'shy';
  }
  if (boldness < 55 || displayedStage === 1) {
    return seed % 3 === 0 ? 'tease' : seed % 2 === 0 ? 'shy' : 'fluster';
  }
  if (boldness < 80 || displayedStage <= 3) {
    return seed % 3 === 0 ? 'bold' : seed % 2 === 0 ? 'tease' : 'fluster';
  }
  return seed % 3 === 0 ? 'tease' : 'bold';
}

