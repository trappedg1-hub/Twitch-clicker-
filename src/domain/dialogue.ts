/**
 * Live-situation lines: she comments on what is happening in the stream right now (how close the
 * goal is, the hype spike, the mic tier, the viewer list, her own boldness) instead of repeating
 * generic flirty filler.
 */
export interface StreamSituation {
  streamDay: number;
  stage: SubGoalStageIndex;
  subs: number;
  nextGoalSubs: number | null;
  boldness: number;
  hype: number;
  onlineViewers: number;
  micTier: number;
  balance: number;
  seed: number;
}

export function pickSituationLine(s: StreamSituation): string {
  const left = s.nextGoalSubs === null ? 0 : Math.max(0, s.nextGoalSubs - s.subs);
  const total = s.nextGoalSubs ?? 1;
  const nearly = total > 0 && left > 0 && left / total < 0.08;
  const pool: string[] = [];

  if (nearly) {
    pool.push(
      `Ещё ${left} сабов... я, конечно, всё контролирую, но я уже мысленно готова. Не торопитесь. Торопитесь.`,
      `${left} сабов до цели, и у меня почему-то дрожит голос. Это от волнения, а не от холода!`,
    );
  }
  if (s.hype >= 78) {
    pool.push(
      'Хапнул вас хайп-бар? У меня от него внутри всё переворачивается, и это не метафора...',
      'Чат на пределе, я слышу, как у меня сбивается дыхание. Мне пора краснеть или уже поздно?',
    );
  }
  if (s.micTier >= 8) {
    pool.push(
      'С таким микрофоном слышно каждый мой вдох. Вы же это специально купили, да? Специально.',
      'Шумоподавление выключено... то есть нет, оно не выключено. Я просто очень тихо дышу~',
    );
  } else if (s.micTier === 0) {
    pool.push('Мне даже слышно, как я саму себя переспрашиваю. Надо бы нормальный микрофон, чат.');
  }
  if (s.onlineViewers >= 900) {
    pool.push(
      `Вас ${s.onlineViewers}... я листнула список зрителей и он не закончился. У меня мурашки.`,
      'Я вижу, что вас больше, чем людей в моём дворе. Это пугает и очень льстит, честно.',
    );
  } else if (s.onlineViewers < 30) {
    pool.push('Нас пока мало, и это самое уютное время: вы ещё не успели меня совсем раздеть взглядом.');
  }
  if (s.balance >= 40000) {
    pool.push('У вас, кажется, больше денег, чем у всего моего района. Это ответственность, чат!');
  }
  if (s.boldness >= 70 && s.stage < 4) {
    pool.push(
      'Мне нравится, куда это идёт, и я почти перестала это прятать. Почти — не «совсем», я честная.',
      'Знаете, что самое странное? Я уже сама выбираю, когда краснеть. Это почти власть, чат.',
    );
  }
  // Ghost day: the sheet is the story, so she narrates the costume on top of the numbers.
  const cosplayPool: string[] = [];
  if (s.streamDay === 3) {
    cosplayPool.push(
      'Это простыня, чат. Я её резала ножницами в четыре утра, так что «Бу!» — и продолжайте смотреть.',
      `«Сбрось простыню» — слышу. Ответ: сначала ${left} сабов до цели. Призраки торгуются медленно.`,
      'Сетка внизу, простыня сверху, контраст посередине. Я не придумала это, это референс, я лишь исполнитель~',
      'Простыня шуршит в микрофон. Вы же это купили, да? Этот шорох — ваш любимый звук, я видела статистику.',
    );
    if (s.stage === 0) {
      cosplayPool.push('Я пока белый прямоугольник с глазами. Да, я знаю, что вы ждёте. Нет, я не тороплюсь.');
    }
    if (s.stage === 1) {
      cosplayPool.push('Плечо открыто, ткань держится на честном слове и на вашей выдержке, чат.');
    }
    if (s.stage === 2) {
      cosplayPool.push('Ткань обтянула силуэт, и я сделала вид, что это задумка художника. Это была задумка физики.');
    }
    if (s.stage === 3) {
      cosplayPool.push('Простыня короткая, боди высокое, сетка на месте. Призрак стал откровеннее, чем планировалось~');
    }
    if (s.stage === 4) {
      cosplayPool.push('Плащ из простыни, боди, сетка. Костюм закрыт на сто процентов — и я это сделала сама.');
    }
  }
  if (cosplayPool.length > 0 && Math.abs(s.seed) % 3 !== 2) {
    return cosplayPool[Math.abs(s.seed) % cosplayPool.length]!;
  }
  if (s.streamDay === 2 && s.stage === 0) {
    pool.push('Я сегодня в худи и всё помню про вчерашнее. Так что не надейтесь, что это будет быстро.');
  }
  if (pool.length === 0) {
    pool.push(
      'Я тут, чат открыт, сабы капают — живём, Мия на месте, смущение тоже~',
      'Ничего не происходит, и это прекрасно. Я сижу, дышу, вы смотрите. Идеальный вечер.',
    );
  }
  return pool[Math.abs(s.seed) % pool.length]!;
}

