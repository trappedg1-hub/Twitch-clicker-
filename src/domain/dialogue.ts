export function pickDialogueLine(
  zone: TapZoneId,
  band: DialogueBand,
  tapCount: number,
): string {
  const pool = ZONE_DIALOGUES[zone][band];
  return pool[tapCount % pool.length] ?? pool[0] ?? '';
}
