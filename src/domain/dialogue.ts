export function pickIdleTeaseLine(
  displayedStage: SubGoalStageIndex,
  seed: number,
  streamDay = 1,
): string {
  const w = getWardrobe(streamDay, displayedStage);
  if (streamDay === 5) {
    const stagePool = DAY5_IDLE_BY_STAGE[displayedStage] ?? [];
    const picked = pickFromPool([stagePool], w, seed);
    if (picked !== safeWardrobeLine(w, seed)) return picked;
    return pickFromPool([DAY5_IDLE_BY_STAGE[displayedStage === 0 ? 0 : 4] ?? [], stagePool], w, seed);
  }
  if (streamDay === 4) {
    const stagePool = DAY4_IDLE_BY_STAGE[displayedStage] ?? [];
    const picked = pickFromPool([stagePool], w, seed);
    if (picked !== safeWardrobeLine(w, seed)) return picked;
    return pickFromPool([DAY4_IDLE_BY_STAGE[displayedStage === 0 ? 0 : 4] ?? [], stagePool], w, seed);
  }
  if (streamDay === 3) {
    const stagePool = DAY3_IDLE_BY_STAGE[displayedStage] ?? [];
    const picked = pickFromPool([stagePool], w, seed);
    if (picked !== safeWardrobeLine(w, seed)) return picked;
    return pickFromPool([DAY2_IDLE_LINES, stagePool], w, seed);
  }
  if (streamDay === 2) {
    const stagePool = DAY2_IDLE_BY_STAGE[displayedStage] ?? [];
    const picked = pickFromPool([stagePool], w, seed);
    if (picked !== safeWardrobeLine(w, seed)) return picked;
    return pickFromPool([DAY2_IDLE_LINES, stagePool], w, seed);
  }
  const pool =
    SPONTANEOUS_IDLE_TEASE_LINES[displayedStage] ?? SPONTANEOUS_IDLE_TEASE_LINES[0]!;
  return pickFromPool([pool], w, seed);
}

export function pickReactionCalloutTag(
  zone: TapZoneId,
  isFever: boolean,
  seed: number,
): string {
  if (isFever && seed % 2 === 0) {
    const feverTags = ['ЖАРА В ЭФИРЕ! ♥', 'ПУЛЬС НА ПРЕДЕЛЕ ★', 'МУРАШКИ ПО КОЖЕ ♥', 'ЧАТ КИПИТ!! ★'];
    return feverTags[Math.abs(seed) % feverTags.length]!;
  }
  const pool = REACTION_CALLOUT_TAGS[zone];
  return pool[Math.abs(seed) % pool.length]!;
}
