/**
 * Every line she speaks is checked against the outfit that is actually on the plate. If a pool
 * turns out to be entirely wrong for this stage (chat begs for "bare feet" while the golf socks
 * are still on), we fall back to a line that can only be true right now - so a subtitle can
 * never contradict the art again.
 */
function pickFromPool(
  pools: readonly (readonly string[])[],
  w: Wardrobe,
  seed: number,
  zone?: TapZoneId,
): string {
  const usable: string[] = [];
  for (const pool of pools) {
    for (const line of pool) {
      if (contradictsWardrobe(line, w, zone) === null) usable.push(line);
    }
  }
  if (usable.length === 0) {
    const fallback = safeWardrobeLine(w, seed);
    return contradictsWardrobe(fallback, w, zone) === null
      ? fallback
      : 'М-м! Вы пишете так, что я уже забываю, о чём вообще был стрим... ♥';
  }
  return usable[Math.abs(seed) % usable.length]!;
}

/**
 * Tap reaction for the "she reacts to every click" days. Stage-specific lines come first (that is
 * the "she is actually watching the stream" feeling), then the day-wide pool so one zone never goes
 * silent, then the guaranteed wardrobe-safe fallback.
 */
export function pickStageTapLine(
  zone: TapZoneId,
  seed: number,
  displayedStage: SubGoalStageIndex = 0,
  streamDay = 2,
): string {
  const w = getWardrobe(streamDay, displayedStage);
  if (streamDay === 5) {
    const stagePool5 = DAY5_STAGE_ZONE_LINES[displayedStage]?.[zone] ?? [];
    const picked5 = pickFromPool([stagePool5], w, seed, zone);
    if (picked5 !== safeWardrobeLine(w, seed)) return picked5;
    return pickFromPool([DAY5_TAP_LINES[zone] ?? [], stagePool5], w, seed, zone);
  }
  if (streamDay === 4) {
    const stagePool4 = DAY4_STAGE_ZONE_LINES[displayedStage]?.[zone] ?? [];
    const picked4 = pickFromPool([stagePool4], w, seed, zone);
    if (picked4 !== safeWardrobeLine(w, seed)) return picked4;
    return pickFromPool([DAY4_TAP_LINES[zone] ?? [], stagePool4], w, seed, zone);
  }
  const byStage = streamDay === 3 ? DAY3_STAGE_ZONE_LINES : DAY2_STAGE_ZONE_LINES;
  const dayPool = streamDay === 3 ? DAY3_TAP_LINES[zone] ?? [] : DAY2_TAP_LINES[zone] ?? [];
  const stagePool = byStage[displayedStage]?.[zone] ?? [];
  const picked = pickFromPool([stagePool], w, seed, zone);
  if (picked !== safeWardrobeLine(w, seed)) return picked;
  return pickFromPool([dayPool, stagePool], w, seed, zone);
}

/** Back-compat name used by Day 2 call sites. */
export function pickDay2TapLine(
  zone: TapZoneId,
  seed: number,
  displayedStage: SubGoalStageIndex = 0,
): string {
  return pickStageTapLine(zone, seed, displayedStage, 2);
}

