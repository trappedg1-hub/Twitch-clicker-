#!/usr/bin/env python3
"""
Processes the Day 2 Sub Goal ladder plates (stages 1..4) so every one of them shares
the EXACT canonical face of the approved Day 2 stage-0 render (art-studio/raw/t2_day2_outfit_v7.png),
which is itself face-locked to the Day 1 master. Same chair, same framing, same scale.

Day 2 ladder (1500 / 2000 / 2500 / 5000 subs), fan-service rising step by step:
- stage 0 (0 subs)     -> heroine_t2_s0.webp  beige pullover hoodie + shorts + straight golf socks
- stage 1 (1500 subs)  -> heroine_t2_s1.webp  grey cropped tee, knees hugged, golf socks slouched
- stage 2 (2000 subs)  -> heroine_t2_s2.webp  black camisole, HOODIE TIED AROUND THE WAIST, socks at the ankles
- stage 3 (2500 subs)  -> heroine_t2_s3.webp  one strap slipped down, hoodie hanging open behind her, leaning in
- stage 4 (5000 subs)  -> heroine_t2_s4.webp  kneeling on the seat toward the webcam, bare feet (the socks only
                                               come off at this very last stage)
"""

import sys
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from process_subgoal_art import remove_plum_matte  # noqa: E402

RAW_DIR = ROOT / "art-studio" / "raw"
OUT_DIR = ROOT / "public" / "art"
QA_DIR = ROOT / ".qa-out"

MASTER = RAW_DIR / "t2_day2_outfit_v7.png"

# Renders that need a small continuity repair, mapped to the plate they must match.
CONTINUITY_FIXES = {"t2_day2_s1_v2.png": "t2_day2_outfit_v7.png", "t2_day2_s3_v3.png": "t2_day2_s3.png"}

# The face patch box HeroineRig was authored against (plate pixels, 1024x1526 space).
CANON_FACE_BOX = (338, 61, 348, 397)
ANCHORS_TS = ROOT / "src" / "heroine" / "faceAnchors.ts"


def edges(img: np.ndarray) -> np.ndarray:
    g = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
    return cv2.Canny(g, 40, 120)


def find_face_box(plate: np.ndarray, ref_plate: np.ndarray, ref_box: tuple[int, int, int, int]) -> tuple[int, int, int, int]:
    """
    Locate ref_box's content on `plate` with a scale-aware edge match.

    The leaning Day 2 plates (straps down, kneeling finale) draw her head larger and a bit
    higher than the canonical box, which is exactly why pasting the master's face onto them
    produced a ghost eye. So we never paste: we measure, keep each plate's own face, and hand
    the measured box to the rig so the emotion/blink patches land on HER eyes on every stage.
    """
    x, y, w, h = ref_box
    ref = edges(ref_plate[y : y + h, x : x + w])
    target = edges(plate)
    best = (-1.0, (x, y, w, h))
    for pct in range(78, 133, 2):
        s = pct / 100.0
        tw, th = int(round(w * s)), int(round(h * s))
        if tw < 24 or th < 24 or tw >= target.shape[1] or th >= target.shape[0]:
            continue
        tmpl = cv2.resize(ref, (tw, th), interpolation=cv2.INTER_AREA)
        res = cv2.matchTemplate(target, tmpl, cv2.TM_CCOEFF_NORMED)
        _, score, _, loc = cv2.minMaxLoc(res)
        if score > best[0]:
            best = (float(score), (int(loc[0]), int(loc[1]), tw, th))
    score, box = best
    print(f"    face anchor: box={box} edge score={score:.3f}")
    return box


def write_anchors(anchors: dict[str, tuple[int, int, int, int]]) -> None:
    lines = [
        "/**",
        " * Face patch anchors, generated by scripts/process_day2_ladder_art.py.",
        " *",
        " * Box = (x, y, w, h) in plate pixels (1024x1526) where the canonical emotion/blink patch",
        " * content lands on THAT plate. Day 1 stages and Day 2 stage 0 use the authored box;",
        " * the leaning Day 2 stages get their head measured, so blush/blink never sit on her",
        " * neck or float off her cheek when she moves closer to the webcam.",
        " */",
        "",
        "export interface FaceAnchor {",
        "  readonly x: number;",
        "  readonly y: number;",
        "  readonly w: number;",
        "  readonly h: number;",
        "}",
        "",
        "export const CANONICAL_FACE: FaceAnchor = "
        + "{ x: %d, y: %d, w: %d, h: %d };" % CANON_FACE_BOX,
        "",
        "/** Keyed by plate file name (as shipped in public/art). */",
        "export const FACE_ANCHORS: Record<string, FaceAnchor> = {",
    ]
    for name, (bx, by, bw, bh) in anchors.items():
        lines.append(f"  {name!r}: {{ x: {bx}, y: {by}, w: {bw}, h: {bh} }},".replace("'", '"'))
    lines.append("};")
    lines.append("")
    lines.append("export function faceAnchorFor(plateUrl: string): FaceAnchor {")
    lines.append("  const name = plateUrl.split('/').pop() ?? '';")
    lines.append("  return FACE_ANCHORS[name] ?? CANONICAL_FACE;")
    lines.append("}")
    lines.append("")
    ANCHORS_TS.write_text("\n".join(lines))
    print(f"anchors -> {ANCHORS_TS.relative_to(ROOT)}")


def unify_nail_polish(rgb_np: np.ndarray, ref_np: np.ndarray) -> np.ndarray:
    """Repaint saturated-red nails with the reference plate's dark plum manicure (continuity)."""
    H0, W0, _ = rgb_np.shape
    yy, xx = np.mgrid[0:H0, 0:W0]
    band = (yy > int(H0 * 0.48)) & (yy < int(H0 * 0.74)) & ((xx < int(W0 * 0.32)) | (xx > int(W0 * 0.60)))

    def red_mask(a: np.ndarray) -> np.ndarray:
        r = a[:, :, 0].astype(np.int16)
        g = a[:, :, 1].astype(np.int16)
        b = a[:, :, 2].astype(np.int16)
        return band & (r > 105) & ((r - g) > 50) & ((r - b) > 40) & (g < 95)

    src = red_mask(rgb_np)
    if not src.any():
        return rgb_np
    ref = red_mask(ref_np)
    target = np.median(ref_np[ref], axis=0) if ref.any() else np.array([104.0, 62.0, 118.0])
    src_lum = max(float(np.mean(rgb_np[src].mean(axis=1))), 1.0)
    rel = rgb_np[src].mean(axis=1) / src_lum  # keep each nail's own highlight/shade
    out = rgb_np.astype(np.float32).copy()
    out[src] = np.clip(target[None, :] * rel[:, None], 0, 255)
    alpha = (
        cv2.GaussianBlur((src.astype(np.uint8) * 255), (0, 0), sigmaX=0.8)[..., None].astype(np.float32)
        / 255.0
    )
    return np.clip(rgb_np.astype(np.float32) * (1.0 - alpha) + out * alpha, 0, 255).astype(np.uint8)

# Day 2 ladder mapping approved by the user:
# 1500 -> tee without the hoodie (t2_day2_s1) | 2000 -> hoodie tied on the waist (t2_day2_s3)
# 2500 -> strap slipped, hoodie hanging behind (t2_day2_s3_v2) | 5000 -> kneeling finale (t2_day2_s4_pose_a)
LADDER = [
    ("t2_day2_s1_v2.png", "heroine_t2_s1.webp"),
    ("t2_day2_s3.png", "heroine_t2_s2.webp"),
    ("t2_day2_s3_v3.png", "heroine_t2_s3.webp"),
    ("t2_day2_s4_pose_a.png", "heroine_t2_s4.webp"),
]


def plate_rgb(raw_path: Path, size: tuple[int, int]) -> np.ndarray:
    """Load a render at plate size WITHOUT pasting the master's face over it.

    Pasting is what left a ghost eye + a hard blush ellipse on the two leaning plates: their heads
    are drawn bigger and higher, so the canonical face landed half off her own. The plates are
    already edits of the accepted Day 2 art, so their own face is the canonical one — we keep it.
    """
    im = Image.open(raw_path).convert("RGB")
    if im.size != size:
        im = im.resize(size, Image.Resampling.LANCZOS)
    return np.array(im)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    QA_DIR.mkdir(parents=True, exist_ok=True)

    master_im = Image.open(MASTER).convert("RGB")
    master_np = np.array(master_im)
    H0, W0, _ = master_np.shape

    target_size = Image.open(OUT_DIR / "heroine_t2_s0.webp").size
    sx, sy = target_size[0] / W0, target_size[1] / H0
    print(f"Master {W0}x{H0} -> target plate {target_size[0]}x{target_size[1]}")

    # Canonical patch box expressed in master space (it is authored in plate space).
    cx, cy, cw, ch = CANON_FACE_BOX
    ref_box = (int(cx / sx), int(cy / sy), int(cw / sx), int(ch / sy))

    anchors: dict[str, tuple[int, int, int, int]] = {}

    def anchor_for(rgb: np.ndarray, out_name: str) -> None:
        bx, by, bw, bh = find_face_box(rgb, master_np, ref_box)
        anchors[out_name] = (int(bx * sx), int(by * sy), int(bw * sx), int(bh * sy))

    # Stage 0 is already shipped and face-locked: measure it too so the patch sits exactly on her.
    stage0_rgb = plate_rgb(MASTER, (W0, H0))
    anchor_for(stage0_rgb, "heroine_t2_s0.webp")

    for raw_name, out_name in LADDER:
        rgb = plate_rgb(RAW_DIR / raw_name, (W0, H0))
        if CONTINUITY_FIXES.get(raw_name):
            ref_np = np.array(Image.open(RAW_DIR / CONTINUITY_FIXES[raw_name]).convert("RGB"))
            if ref_np.shape != rgb.shape:
                ref_np = np.array(Image.fromarray(ref_np).resize((rgb.shape[1], rgb.shape[0])))
            before = rgb.copy()
            rgb = unify_nail_polish(rgb, ref_np)
            changed = int(np.sum(np.abs(rgb.astype(np.int16) - before.astype(np.int16)).max(axis=2) > 12))
            if changed:
                print(f"    continuity: nail polish unified against {CONTINUITY_FIXES[raw_name]} ({changed} px repainted)")
        anchor_for(rgb, out_name)
        rgba_im = remove_plum_matte(rgb, target_size)
        out_path = OUT_DIR / out_name
        rgba_im.save(out_path, format="WEBP", quality=92, method=6)
        alpha = np.array(rgba_im)[:, :, 3:4].astype(np.float32) / 255.0
        print(
            f"saved {out_path.relative_to(ROOT)} ({out_path.stat().st_size // 1024} KB) "
            f"coverage={float(np.mean(alpha)):.3f} anchor={anchors[out_name]}"
        )

    # Day 1 plates share the authored box; emit them explicitly so the rig has one lookup path.
    for i in range(5):
        anchors.setdefault(f"heroine_t1_s{i}.webp", CANON_FACE_BOX)
    anchors["heroine_t2_s0.webp"] = anchors.get("heroine_t2_s0.webp", CANON_FACE_BOX)
    write_anchors(anchors)

    # Contact sheet: stage 0 + 4 new plates over a mid-grey bed for eyeball QA.
    names = ["heroine_t2_s0.webp"] + [out for _, out in LADDER]
    imgs = [Image.open(OUT_DIR / n).convert("RGBA") for n in names]
    tw, th = 260, 388
    sheet = Image.new("RGBA", (tw * len(imgs), th + 22), (32, 26, 40, 255))
    for idx, im in enumerate(imgs):
        th_im = im.resize((tw, th), Image.Resampling.LANCZOS)
        bed = Image.new("RGBA", (tw, th), (120, 116, 128, 255))
        bed.alpha_composite(th_im)
        sheet.paste(bed, (idx * tw, 22))
    sheet.convert("RGB").save(QA_DIR / "day2_ladder_sheet.png")
    print(f"contact sheet -> {(QA_DIR / 'day2_ladder_sheet.png').relative_to(ROOT)}")


if __name__ == "__main__":
    main()
